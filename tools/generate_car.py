#!/usr/bin/env python3
"""Generate a continuous, smooth sports-coupe body mesh for NASM/OpenGL.
Build-only tool: the compiled game itself remains x86-64 assembly.
Writes a reproducible OBJ model for future Blender edits and an ASM include.
"""
from pathlib import Path
import math

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "build"
OUT.mkdir(exist_ok=True)
SEGMENTS = 48
STATIONS = 49

def envelope(z):
    # Smooth front and rear taper; raised fender shoulders at axle stations.
    end = abs(z) / 1.78
    taper = max(0.12, 1.0 - end**4)
    swell = 0.045 * (math.exp(-((z - 1.05)/.40)**2) +
                      math.exp(-((z + 1.05)/.40)**2))
    width = 0.88 * taper + swell
    centre = .47 + .015 * (1.0 - end)
    height = (.26 + .03 * math.exp(-((z + 1.05)/.60)**2)) * max(.3, taper)
    return width, centre, height

def point(z, a):
    width, centre, height = envelope(z)
    # Rounded shoulders, gentle upper crown, flatter underside.
    co, si = math.cos(a), math.sin(a)
    x = width * math.copysign(abs(co) ** 0.72, co)
    y = centre + height * math.copysign(abs(si) ** 0.78, si)
    return (x, y, z)

rings = []
for i in range(STATIONS):
    z = -1.70 + 3.40 * i / (STATIONS-1)
    rings.append([point(z, 2 * math.pi * j/SEGMENTS)
                  for j in range(SEGMENTS)])

# Face normals for now: robust geometry, no separate ill-defined overlapping ellipsoids.
triangles = []
def wheel_arch(tri):
    # Carve real openings into both flanks at the two axle positions.
    # Otherwise the body mesh occludes half the tire and leaves rims
    # looking like floating silver discs beneath the body.
    x = sum(p[0] for p in tri) / 3
    y = sum(p[1] for p in tri) / 3
    z = sum(p[2] for p in tri) / 3
    if abs(x) < .61:
        return False
    return any(((z-axle)/.48)**2 + ((y-.38)/.46)**2 < 1
               for axle in (-1.05, 1.05))
for i in range(STATIONS-1):
    for j in range(SEGMENTS):
        nxt=(j+1)%SEGMENTS
        a,b,c,d=rings[i][j],rings[i+1][j],rings[i+1][nxt],rings[i][nxt]
        for tri in ((a,b,c),(a,c,d)):
            if not wheel_arch(tri):
                triangles.append(tri)

# Radial normals with normal interpolation for smoothly-shaded body panels.
def normal(v):
    x,y,z=v
    w,cy,h=envelope(z)
    nx=x/max(w*w,.001)
    ny=(y-cy)/max(h*h,.001)
    nz=0.0
    l=math.sqrt(nx*nx+ny*ny+nz*nz)
    return (nx/l,ny/l,nz)

vertices=[p for tri in triangles for p in tri]
normals=[normal(p) for p in vertices]

def asm_float(x):
    # Decimal NASM floating point constants, forced real literal.
    return f"{x:.7f}"

src=["; Automatically generated by tools/generate_car.py. Do not edit.",
     f"%define CAR_MESH_VERTEX_COUNT {len(vertices)}",
     "section .rodata align=16", "car_mesh_vertices:"]
for x,y,z in vertices:
    src.append(f"    dd {asm_float(x)}, {asm_float(y)}, {asm_float(z)}")
src.append("car_mesh_normals:")
for x,y,z in normals:
    src.append(f"    dd {asm_float(x)}, {asm_float(y)}, {asm_float(z)}")
(OUT/"car_mesh.inc").write_text("\n".join(src)+"\n",encoding="utf-8")

# OBJ makes the 3D mesh inspectable and editable in Blender.
obj=["# Ayo Race continuous coupe body mesh"]
for ring in rings:
    for p in ring:
        obj.append("v "+" ".join(asm_float(v) for v in p))
for i in range(STATIONS-1):
    for j in range(SEGMENTS):
        n=(j+1)%SEGMENTS
        a=i*SEGMENTS+j+1;b=(i+1)*SEGMENTS+j+1
        c=(i+1)*SEGMENTS+n+1;d=i*SEGMENTS+n+1
        obj.append(f"f {a} {b} {c}")
        obj.append(f"f {a} {c} {d}")
(OUT/"ayo_race_coupe.obj").write_text("\n".join(obj)+"\n",encoding="utf-8")
print(f"Generated continuous sports coupe body: {len(vertices)//3} triangles")
